type Make = (prefix: string, tag: string) => Router;

export function registerModules(make: Make): void {
  make('', 'System').get('/health', { auth: 'public', summary: 'Liveness and database readiness' }, async () => {
    await db().execute(sql`SELECT 1`);
    return { status: 'ok', time: new Date().toISOString() };
  });
  registerAuthRoutes(make('/auth', 'Authentication'));
  registerCompanyRoutes(make('/company', 'Company'));
  registerUserRoutes(make('/users', 'Users'));
  registerRoleRoutes(make('/roles', 'Roles & permissions'));
  registerTaxRoutes(make('/tax-rates', 'Tax'));
  registerApprovalRuleRoutes(make('/approval-rules', 'Approvals'));
  registerApprovalRoutes(make('/approvals', 'Approvals'));
  registerWarehouseRoutes(make('/warehouses', 'Warehouses & locations'));
  registerProductRoutes(make('/products', 'Products'));
  registerCategoryRoutes(make('/product-categories', 'Products'));
  registerBatchRoutes(make('/batches', 'Inventory'));
  registerSerialRoutes(make('/serials', 'Inventory'));
  registerInventoryRoutes(make('/inventory', 'Inventory'));
  registerTransferRoutes(make('/transfers', 'Transfers'));
  registerSupplierRoutes(make('/suppliers', 'Suppliers'));
  registerPurchaseOrderRoutes(make('/purchase-orders', 'Purchasing'));
  registerPurchaseReturnRoutes(make('/purchase-returns', 'Purchasing'));
  registerReceivingRoutes(make('/receiving', 'Receiving'));
  registerPutawayRoutes(make('/putaway', 'Putaway'));
  registerCustomerRoutes(make('/customers', 'Customers'));
  registerSalesOrderRoutes(make('/sales-orders', 'Sales orders'));
  registerPickingRoutes(make('/picking', 'Picking'));
  registerPackingRoutes(make('/packing', 'Packing'));
  registerDispatchRoutes(make('/dispatch', 'Dispatch'));
  registerShipmentRoutes(make('/shipments', 'Dispatch'));
  registerReturnRoutes(make('/returns', 'Returns'));
  registerCountRoutes(make('/stock-counts', 'Stock counts'));
  registerInvoiceRoutes(make('/invoices', 'Billing'));
  registerBillRoutes(make('/supplier-bills', 'Billing'));
  registerPaymentRoutes(make('/payments', 'Billing'));
  registerExpenseRoutes(make('/expenses', 'Expenses'));
  registerStorageBillingRoutes(make('/storage-billing', 'Storage billing'));
  registerProfitabilityRoutes(make('/profitability', 'Profitability'));
  registerDashboardRoutes(make('/dashboard', 'Dashboard'));
  registerAlertRoutes(make('/alerts', 'Alerts'));
  registerAuditRoutes(make('/audit', 'Audit'));
  registerSearchRoutes(make('/search', 'Search'));
  registerReportRoutes(make('/reports', 'Reports'));
  registerImportRoutes(make('/imports', 'Import / export'));
  registerIntegrationRoutes(make('/integrations', 'Integrations'));
  registerWebhookRoutes(make('/webhooks', 'Integrations'));
  registerSupportRoutes(make('/support', 'Support'));
  registerPlatformRoutes(make('/platform', 'Platform administration'));
  registerAiRoutes(make('/ai', 'AI Copilot'));
}
